#!/usr/bin/env bash
set -euo pipefail

repo_root="${BRILLIANT_REPO_ROOT:-/workspace/briliant-ai-lab}"
tool_root="${BRILLIANT_TOOL_ROOT:-/workspace/.brilliant-agent-tools}"
skills_root="$repo_root/.agents/skills"
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

test -f "$repo_root/package-lock.json"
test -d "$repo_root/docs"
mkdir -p "$skills_root" "$tool_root"
find "$repo_root/docs" -type f -print0 | sort -z | xargs -0 -r sha256sum > "$scratch/docs.before"

# Pin all CLI packages. npm verifies their registry integrity during install.
npm --cache "${TMPDIR:-/tmp}/npm-brilliant-agents" install \
  --prefix "$tool_root" --ignore-scripts --no-audit --no-fund \
  opencode-linux-x64@1.19.6 @fission-ai/openspec@2.2.0 ui-ux-pro-max-cli@2.15.0
test "$(env HOME="$tool_root/home" XDG_DATA_HOME="$tool_root/home/share" XDG_CONFIG_HOME="$tool_root/home/config" XDG_CACHE_HOME="$tool_root/home/cache" XDG_STATE_HOME="$tool_root/home/state" "$tool_root/node_modules/opencode-linux-x64/bin/opencode" --version)" = "1.19.6"
test "$("$tool_root/node_modules/.bin/openspec" --version)" = "2.2.0"
test "$("$tool_root/node_modules/.bin/uipro" --version)" = "2.15.0"

fetch_pinned() {
  local name="$1" url="$2" sha="$3" path="$scratch/$1"
  [[ "$sha" =~ ^[0-9a-f]{40}$ ]]
  git init -q "$path"
  git -C "$path" remote add origin "$url"
  git -C "$path" fetch -q --depth=1 origin "$sha"
  git -C "$path" checkout -q --detach FETCH_HEAD
  test "$(git -C "$path" rev-parse HEAD)" = "$sha"
}

copy_skill() {
  local source="$1" destination="$2"
  test -d "$source"
  test -f "$source/SKILL.md"
  if [[ ! -e "$destination" ]]; then
    cp -a "$source" "$destination"
  fi
  test -f "$destination/SKILL.md"
}

fetch_pinned ponytail https://github.com/DietrichGebert/ponytail.git ebd8654c2c627f721eb8f9c0d1bd4090a29f9e10
fetch_pinned mattpocock https://github.com/mattpocock/skills.git 6f7f7831a625f040a8e06a0e7954826b87ce775a
fetch_pinned openspec https://github.com/Fission-AI/OpenSpec.git f1cd852f4edce22b8df9548a4df889172ca8ff25
copy_skill "$scratch/ponytail/skills/ponytail" "$skills_root/ponytail"
for skill in tdd diagnosing-bugs code-review codebase-design; do
  copy_skill "$scratch/mattpocock/skills/engineering/$skill" "$skills_root/$skill"
done
copy_skill "$scratch/mattpocock/skills/productivity/grill-me" "$skills_root/grill-me"

# The official universal installer supplies a skill with portable script paths.
if [[ ! -f "$skills_root/ui-ux-pro-max/SKILL.md" ]]; then
  (cd "$repo_root" && "$tool_root/node_modules/.bin/uipro" init --ai universal)
fi
test -f "$skills_root/ui-ux-pro-max/SKILL.md"
test -f "$skills_root/ui-ux-pro-max/scripts/search.py"

# OpenSpec CLI initialization creates the project and both tool integrations.
# Its managed skills are generated by the CLI, not copied from its Git tree.
if [[ ! -f "$repo_root/openspec/config.yaml" || ! -f "$skills_root/openspec-propose/SKILL.md" ]]; then
  (cd "$repo_root" && env HOME="$tool_root/home" XDG_CONFIG_HOME="$tool_root/home/config" OPENSPEC_TELEMETRY=0 OPENSPEC_NO_ANIMATION=1 "$tool_root/node_modules/.bin/openspec" init --scope project --tools codex,opencode)
fi
test -f "$repo_root/openspec/config.yaml"
test -f "$skills_root/openspec-propose/SKILL.md"
test -f "$skills_root/openspec-apply-change/SKILL.md"
# Keep the six optional OpenSpec skills already present in this workspace.
# Project initialization above remains the source of the core integration.
for skill in openspec-new-change openspec-continue-change openspec-ff-change openspec-bulk-archive-change openspec-verify-change openspec-onboard; do
  copy_skill "$scratch/openspec/skills/$skill" "$skills_root/$skill"
done
for installed_skill in "$skills_root"/openspec*; do
  test -f "$installed_skill/SKILL.md"
done

# Project configuration is also kept as reviewable files for Git tracking.
if [[ ! -e "$repo_root/opencode.json" ]]; then
  cat > "$repo_root/opencode.json" <<'JSON'
{
  "$schema": "https://opencode.ai/config.json",
  "enabled_providers": ["openrouter"],
  "model": "openrouter/particle-ai/particle-1:free",
  "small_model": "openrouter/particle-ai/particle-1:free",
  "permission": {
    "bash": {"*git*push*": "deny", "*deploy*": "deny", "*": "ask"},
    "read": {".env*": "deny", "**/.env*": "deny"}
  }
}
JSON
fi
node - "$repo_root/opencode.json" <<'NODE'
const fs = require('node:fs');
const config = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const free = 'openrouter/particle-ai/particle-1:free';
if (config.model !== free || config.small_model !== free ||
    JSON.stringify(config.enabled_providers) !== JSON.stringify(['openrouter']) ||
    config.permission?.bash?.['*'] !== 'ask' ||
    config.permission?.bash?.['*git*push*'] !== 'deny' ||
    config.permission?.bash?.['*deploy*'] !== 'deny' ||
    config.permission?.read?.['.env*'] !== 'deny' ||
    config.permission?.read?.['**/.env*'] !== 'deny') {
  throw new Error('OpenCode configuration must enforce the approved free model and permissions');
}
NODE
if [[ ! -e "$repo_root/AGENTS.md" ]]; then
  cat > "$repo_root/AGENTS.md" <<'MD'
# Agent roles and data handling

The Codex Lead Agent handles planning, architecture, code review, and final validation.
OpenCode handles only small, well-defined, low-risk implementation tasks delegated by the Codex Lead Agent.
If particle-ai/particle-1:free is unavailable, rate-limited, or errors, stop and report the error. Never switch models.

Never read, print, summarize, transmit, or include API keys, .env files, credentials, secrets, or sensitive data in model context.
OPENROUTER_API_KEY is only for OpenCode authentication; never print it or write it to files.

OpenCode shell commands require approval. Git push and deployment are denied.
MD
fi

mkdir -p "$repo_root/.agents/bin"
if [[ ! -e "$repo_root/.agents/bin/opencode" ]]; then
  cat > "$repo_root/.agents/bin/opencode" <<'SH'
#!/usr/bin/env bash
set -euo pipefail
tool_root="${BRILLIANT_TOOL_ROOT:-/workspace/.brilliant-agent-tools}"
opencode_state_root="$tool_root/home"
exec env HOME="$opencode_state_root" \
  XDG_DATA_HOME="$opencode_state_root/share" \
  XDG_CONFIG_HOME="$opencode_state_root/config" \
  XDG_CACHE_HOME="$opencode_state_root/cache" \
  XDG_STATE_HOME="$opencode_state_root/state" \
  "$tool_root/node_modules/opencode-linux-x64/bin/opencode" "$@"
SH
  chmod 755 "$repo_root/.agents/bin/opencode"
fi
test "$(BRILLIANT_TOOL_ROOT="$tool_root" "$repo_root/.agents/bin/opencode" --version)" = "1.19.6"
find "$repo_root/docs" -type f -print0 | sort -z | xargs -0 -r sha256sum > "$scratch/docs.after"
cmp "$scratch/docs.before" "$scratch/docs.after"
